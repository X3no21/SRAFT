#!/bin/bash

# Smart MQTTS Broker Management Script
# Usage: 
#   sudo ./setup_mqtts_broker.sh     → Restart broker only
#   sudo ./setup_mqtts_broker.sh -r  → Full reinstall/reconfigure

set -e

if [ -z "$SUDO_USER" ]; then
    echo "This script must be run with 'sudo'."
    exit 1
fi

USER_HOME=$(eval echo ~$SUDO_USER)
BROKER_IP=$(hostname -I | awk '{print $1}')

if [ -z "$BROKER_IP" ]; then
    echo "Could not detect the broker's IP address."
    exit 1
fi

CERT_DIR="/etc/mosquitto/certs"
MOSQUITTO_CONF_DIR="/etc/mosquitto/conf.d"
MOSQUITTO_CONF_FILE="${MOSQUITTO_CONF_DIR}/mtls.conf"
PROJECT_CERTS_DIR="$(dirname "$(dirname "$(realpath "$0")")")/../main/certs"

DO_FULL_SETUP=false
if [ "$1" == "-r" ]; then
    DO_FULL_SETUP=true
fi

do_full_setup() {
    echo "=== Full MQTTS Broker Setup ==="
    echo "Broker IP: ${BROKER_IP}"
    
    echo -e "\n[1/4] Installing Mosquitto..."
    apt-get update -qq
    apt-get install -y mosquitto mosquitto-clients openssl
    
    echo -e "\n[2/4] Copying certificates from firmware..."
    mkdir -p "$CERT_DIR"
    
    if [ ! -d "$PROJECT_CERTS_DIR" ]; then
        echo "Certificate directory not found: $PROJECT_CERTS_DIR"
        exit 1
    fi
    
    cp "$PROJECT_CERTS_DIR/ca.crt" "$CERT_DIR/"
    cp "$PROJECT_CERTS_DIR/device.crt" "$CERT_DIR/broker.crt"
    cp "$PROJECT_CERTS_DIR/device.key" "$CERT_DIR/broker.key"
    
    # Fix permissions for mosquitto user
    chown -R mosquitto:mosquitto "$CERT_DIR"
    chmod 755 "$CERT_DIR"
    chmod 644 "$CERT_DIR/ca.crt"
    chmod 644 "$CERT_DIR/broker.crt"
    chmod 600 "$CERT_DIR/broker.key"
    
    echo "Certificates copied to $CERT_DIR with correct permissions"
    
    echo -e "\n[3/4] Creating Mosquitto configuration..."
    mkdir -p "$MOSQUITTO_CONF_DIR"
    
    cat > "$MOSQUITTO_CONF_FILE" << EOF
# MQTTS Broker Configuration - mTLS enabled
# Auto-generated by setup_mqtts_broker.sh

port 8883
allow_anonymous false
protocol mqtt

# Certificate paths (using hardcoded certs from firmware)
cafile ${CERT_DIR}/ca.crt
keyfile ${CERT_DIR}/broker.key
certfile ${CERT_DIR}/broker.crt

# Require client certificates (mTLS)
require_certificate true
use_identity_as_username true
EOF
    
    echo "✓ Configuration created at $MOSQUITTO_CONF_FILE"
    
    echo -e "\n[4/4] Restarting Mosquitto..."
    systemctl enable mosquitto
    systemctl restart mosquitto
    sleep 2
    
    echo "Full setup completed!"
    systemctl status mosquitto --no-pager | head -10
}

do_restart() {
    echo "=== Restarting MQTTS Broker ==="
    
    if ! systemctl is-active --quiet mosquitto; then
        echo "Mosquitto is not installed or not running. Use -r flag for full setup."
        exit 1
    fi
    
    systemctl restart mosquitto
    sleep 1
    
    echo "Mosquitto restarted"
    systemctl status mosquitto --no-pager | head -5
}

if [ "$DO_FULL_SETUP" = true ]; then
    do_full_setup
else
    do_restart
fi

echo -e "\nBroker listening on: mqtts://${BROKER_IP}:8883"